# ============================================================
# step6-scope-child : step6-return.ps1 の 6 で呼ばれる側のスクリプト
# ------------------------------------------------------------
# やること
#   親（呼んだ側）の変数を読み、代入し、変数と関数を作る。
#   呼び方（& / . / pwsh -File）によって、親に何が残るかを step6-return.ps1 で確かめる
#
# 覚えておくこと
#   - このスクリプトは、わざと親の $x と $arr を引数なしで読んでいる（よくない書き方の例）。
#     単体で実行したり pwsh -File で呼んだりすると、どちらも空になる
#   - ふつうは、使う値を param(...) で受け取り、結果は戻り値で返す（step6-sub.ps1 を参照）
# ============================================================

Write-Host "  子：親の x を読む → [$x]"

$x        = "子で代入"                     # & ではこのスクリプトの中だけ。. では親の $x を上書きする
$script:y = "子の script: で代入"          # $script: は「このスクリプト自身」。& では親に届かない
$newVar   = "子で作った変数"               # & では終わると消える。. では親に残る

# 親の配列の中身を書き換える（& でも親に反映される）
# pwsh -File で呼ぶと親の $arr は見えず空なので、書き換えない
if ($null -ne $arr) { $arr[0] = "子で書き換え" }

function Child-Func { "子の関数" }          # & では終わると消える。. では親に残る

Write-Host "  子：代入した後の x → [$x]"
