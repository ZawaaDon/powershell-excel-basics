# ============================================================
# step6 : スクリプトから別のスクリプトを呼び出す
# ------------------------------------------------------------
# 学ぶこと
#   - PowerShell のスクリプトから別のスクリプトを呼ぶ（このファイル）
#   - bat ファイルからスクリプトを呼ぶ（step6.bat）
#   - 引数なし / 引数ありの呼び方、戻り値の受け取り方
#
# 使うファイル
#   step6-sub.ps1     : 呼ばれる側（指定セルに文字を書く。引数 -Addr / -Text）
#   step6.bat         : 同じ呼び出しを bat ファイルから行う
#                       最後に step6-macro.ps1 を呼び、マクロで計算した値を bat で受け取る
#                       （for /f で受け取る / 長い部分を変数にまとめる / ファイル経由で終了コードも見る の3通り）
#   step6-macro.ps1   : 呼ばれる側（.xlsm と .xlam のマクロで計算し、結果を1行返す）
#   sample-step6.xlsx : step6-sub.ps1 が毎回 sample-org.xlsx からコピーして作る作業用
#   step6-return.ps1  : 続きの見本（複数の値を返す、関数とスクリプトの中の変数）。単体で実行する
#
# 実行方法
#   .\step6.ps1                 PowerShell から呼ぶ
#   step6.bat をダブルクリック   bat から呼ぶ
#
# 覚えておくこと
#   - & "パス" でスクリプトを実行する。呼んだ先の変数や関数は、こちらには残らない
#     （呼んだ先からこちらの変数は読めるが、頼らずに引数で渡す。step6-return.ps1 の 6 を参照）
#     （関数を読み込みたいときは step3.ps1 の「. パス」を使う）
#   - パスは $PSScriptRoot から書く（カレントフォルダに左右されない）
#   - 引数はカッコとカンマを使わず、空白で区切る
#   - 呼んだ先で止まったエラーは、こちらの try / catch で受けられる
#   - step6-sub.ps1 は毎回コピーし直すので、sample-step6.xlsx に残るのは最後の呼び出しの結果
# ============================================================

# --- 引数なし（step6-sub.ps1 の省略時の値が使われる） ---
& "$PSScriptRoot\step6-sub.ps1"

# --- 引数あり：順番で渡す（param に書かれた順 = Addr, Text） ---
& "$PSScriptRoot\step6-sub.ps1" "G2" "ps から"

# --- 引数あり：名前で渡す（順番は自由） ---
& "$PSScriptRoot\step6-sub.ps1" -Text "名前で指定" -Addr "G3"

# --- 戻り値を受け取る ---
# 変数に入れると画面には出なくなる
$result = & "$PSScriptRoot\step6-sub.ps1" "G4" "戻り値"
Write-Host "戻り値 = $result"
